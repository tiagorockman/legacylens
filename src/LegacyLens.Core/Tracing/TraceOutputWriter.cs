using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using System.Text.RegularExpressions;
using LegacyLens.Core.Tracing.Models;

namespace LegacyLens.Core.Tracing;

public sealed record TraceFile(int Rank, MethodTrace Trace, string JsonPath, string MarkdownPath);

/// <summary>
/// Writes each trace twice: JSON for the LLM layers to consume and Markdown rendering the exact prompt
/// context, so a reviewer can see what the model will be given.
/// </summary>
/// <remarks>
/// Output uses '\n' line endings and relative paths regardless of platform, so the same solution
/// traced on Windows and Linux produces byte-identical files.
/// </remarks>
public static partial class TraceOutputWriter
{
    public const string TracesFolder = "traces";

    public const string IndexFileName = "trace-index.md";

    public static readonly JsonSerializerOptions JsonOptions = new()
    {
        WriteIndented = true,
        NewLine = "\n",
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
        Converters = { new JsonStringEnumConverter() },
    };

    public static async Task<IReadOnlyList<TraceFile>> WriteTracesAsync(
        string outputDirectory,
        IReadOnlyList<MethodTrace> traces,
        CancellationToken cancellationToken = default)
    {
        var tracesDirectory = Path.Combine(outputDirectory, TracesFolder);
        Directory.CreateDirectory(tracesDirectory);
        RemovePreviousTraces(tracesDirectory);

        var files = new List<TraceFile>(traces.Count);
        for (var i = 0; i < traces.Count; i++)
        {
            var trace = traces[i];
            var baseName = $"{i + 1:D3}-{Slug(trace.FullyQualifiedName)}-{ShortHash(trace.Id)}";
            var jsonPath = Path.Combine(tracesDirectory, baseName + ".json");
            var markdownPath = Path.Combine(tracesDirectory, baseName + ".md");

            await File.WriteAllTextAsync(jsonPath, JsonSerializer.Serialize(trace, JsonOptions), cancellationToken);
            await File.WriteAllTextAsync(markdownPath, TracePromptRenderer.Render(trace).ReplaceLineEndings("\n"), cancellationToken);
            files.Add(new TraceFile(i + 1, trace, jsonPath, markdownPath));
        }

        var index = files.Select(f => new
        {
            f.Rank,
            f.Trace.Id,
            f.Trace.FullyQualifiedName,
            f.Trace.Project,
            f.Trace.Complexity,
            f.Trace.Grounding.IsFullyResolved,
            Chunks = f.Trace.Chunks.Count,
            f.Trace.EstimatedTokens,
            Json = Path.GetFileName(f.JsonPath),
            Markdown = Path.GetFileName(f.MarkdownPath),
        });
        await File.WriteAllTextAsync(
            Path.Combine(tracesDirectory, "index.json"),
            JsonSerializer.Serialize(index, JsonOptions),
            cancellationToken);

        return files;
    }

    public static async Task<string> WriteIndexAsync(
        string outputDirectory,
        string solutionName,
        TraceSelection selection,
        int tokenBudget,
        bool appCatIncluded,
        IReadOnlyList<TraceFile> files,
        TimeSpan elapsed,
        CancellationToken cancellationToken = default)
    {
        var traces = files.Select(f => f.Trace).ToList();
        var sb = new StringBuilder();

        sb.AppendLine("# Trace Index");
        sb.AppendLine();
        sb.AppendLine("| | |");
        sb.AppendLine("|---|---|");
        sb.AppendLine($"| **Solution** | `{solutionName}` |");
        sb.AppendLine($"| **Methods traced** | {traces.Count} |");
        sb.AppendLine($"| **Fully resolved by the compiler** | {traces.Count(t => t.Grounding.IsFullyResolved)} of {traces.Count} |");
        sb.AppendLine($"| **Source chunks** | {traces.Sum(t => t.Chunks.Count)} (budget {tokenBudget:N0} tokens each) |");
        sb.AppendLine($"| **Estimated source tokens** | {traces.Sum(t => t.EstimatedTokens):N0} |");
        sb.AppendLine($"| **Elapsed** | {elapsed.TotalSeconds:F1}s |");
        sb.AppendLine($"| **Generated by** | LegacyLens Layer 3 (TraceBuilder), trace schema v{MethodTrace.CurrentSchemaVersion} |");
        sb.AppendLine();

        sb.AppendLine("## Selection");
        sb.AppendLine();
        sb.AppendLine($"- Top {selection.Top} methods by cyclomatic complexity, minimum {selection.MinComplexity}");
        if (selection.MethodFilter is not null)
            sb.AppendLine($"- Method name contains `{selection.MethodFilter}`");
        if (selection.ProjectFilter is not null)
            sb.AppendLine($"- Project `{selection.ProjectFilter}` only");
        sb.AppendLine(selection.IncludeTestProjects ? "- Test projects included" : "- Test projects excluded");
        sb.AppendLine("- Generated code excluded");
        sb.AppendLine(appCatIncluded ? "- AppCAT incidents mapped onto method line ranges" : "- No AppCAT report supplied");
        sb.AppendLine();

        sb.AppendLine("## Traces");
        sb.AppendLine();
        if (files.Count == 0)
        {
            sb.AppendLine("_No methods matched the selection._");
        }
        else
        {
            sb.AppendLine("| # | Method | Project | Complexity | Callers | Calls (solution / external) | Grounding | Chunks | ~Tokens | AppCAT | Trace |");
            sb.AppendLine("|---:|---|---|---:|---:|---:|---|---:|---:|---:|---|");
            foreach (var file in files)
            {
                var t = file.Trace;
                var solutionCalls = t.Callees.Count(c => c.Origin == SymbolOrigin.Source);
                var externalCalls = t.Callees.Count - solutionCalls;
                var grounding = t.Grounding.IsFullyResolved
                    ? "✅ resolved"
                    : $"⚠️ {t.Grounding.CompilerErrors} error(s)";
                var links =
                    $"[md]({TracesFolder}/{Path.GetFileName(file.MarkdownPath)}) · " +
                    $"[json]({TracesFolder}/{Path.GetFileName(file.JsonPath)})";

                sb.AppendLine(
                    $"| {file.Rank} | `{t.FullyQualifiedName}` | {t.Project} | {t.Complexity} | {t.Callers.Count} | " +
                    $"{solutionCalls} / {externalCalls} | {grounding} | {t.Chunks.Count} | {t.EstimatedTokens:N0} | " +
                    $"{t.AppCatIncidents.Count} | {links} |");
            }
        }

        var indexPath = Path.Combine(outputDirectory, IndexFileName);
        await File.WriteAllTextAsync(indexPath, sb.ToString().ReplaceLineEndings("\n"), cancellationToken);
        return indexPath;
    }

    /// <summary>"Nop.Services.Catalog.ProductService.SearchProducts(...)" → "ProductService.SearchProducts".</summary>
    internal static string Slug(string fullyQualifiedName)
    {
        var head = fullyQualifiedName.Split('(')[0];
        string previous;
        do
        {
            previous = head;
            head = GenericArguments().Replace(head, string.Empty);
        }
        while (head != previous);

        var slug = string.Join('.', head.Split('.', StringSplitOptions.RemoveEmptyEntries).TakeLast(2));
        slug = UnsafeFileNameCharacters().Replace(slug, "_");
        return slug.Length <= 80 ? slug : slug[..80];
    }

    /// <summary>Disambiguates overloads while keeping file names stable across runs.</summary>
    internal static string ShortHash(string value) =>
        Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(value)))[..8];

    /// <summary>Only removes files this writer produced, so a reused output folder never keeps stale traces.</summary>
    private static void RemovePreviousTraces(string directory)
    {
        foreach (var file in Directory.EnumerateFiles(directory).ToList())
        {
            var name = Path.GetFileName(file);
            if (name == "index.json" || PreviousTraceFile().IsMatch(name))
                File.Delete(file);
        }
    }

    [GeneratedRegex(@"<[^<>]*>")]
    private static partial Regex GenericArguments();

    [GeneratedRegex(@"[^A-Za-z0-9._-]")]
    private static partial Regex UnsafeFileNameCharacters();

    [GeneratedRegex(@"^\d{3}-.+-[0-9a-f]{8}\.(json|md)$")]
    private static partial Regex PreviousTraceFile();
}
