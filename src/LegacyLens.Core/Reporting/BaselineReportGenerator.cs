using System.Text;
using LegacyLens.Core.Analysis.Models;

namespace LegacyLens.Core.Reporting;

/// <summary>
/// Renders the Phase 1 deliverable `solution-baseline.md`: project inventory, dependency
/// graph, complexity hotspots, deprecated APIs, and AppCAT incident roll-up.
/// </summary>
public static class BaselineReportGenerator
{
    private static readonly TimeSpan MilestoneBudget = TimeSpan.FromMinutes(5);

    public static string GenerateMarkdown(BaselineResult baseline, int topComplexMethods = 20)
    {
        var sb = new StringBuilder();

        sb.AppendLine("# Solution Baseline Report");
        sb.AppendLine();
        sb.AppendLine($"| | |");
        sb.AppendLine($"|---|---|");
        sb.AppendLine($"| **Solution** | `{baseline.SolutionPath}` |");
        sb.AppendLine($"| **Run ID** | `{baseline.RunId}` |");
        sb.AppendLine($"| **Generated (UTC)** | {DateTime.UtcNow:yyyy-MM-dd HH:mm:ss} |");
        sb.AppendLine($"| **Elapsed** | {baseline.Elapsed.TotalSeconds:F1}s {MilestoneBadge(baseline.Elapsed)} |");
        sb.AppendLine($"| **Generated by** | LegacyLens Phase 1 (deterministic core) |");
        sb.AppendLine();

        AppendProjects(sb, baseline);
        AppendDependencyGraph(sb, baseline);
        AppendComplexityHotspots(sb, baseline, topComplexMethods);
        AppendDeprecatedSymbols(sb, baseline);
        AppendAppCat(sb, baseline);
        AppendWorkspaceDiagnostics(sb, baseline);

        return sb.ToString();
    }

    private static string MilestoneBadge(TimeSpan elapsed) =>
        elapsed <= MilestoneBudget ? "(within the <5 min baseline milestone)" : "(exceeds the <5 min baseline milestone)";

    private static void AppendProjects(StringBuilder sb, BaselineResult baseline)
    {
        var errorsByProject = baseline.ProjectSymbols.ToDictionary(
            p => p.ProjectName, p => p.CompilationErrorCount, StringComparer.OrdinalIgnoreCase);

        sb.AppendLine("## Projects");
        sb.AppendLine();
        sb.AppendLine("| Project | Target Framework | Project Refs | Packages | Documents | Build |");
        sb.AppendLine("|---|---|---:|---:|---:|---|");
        foreach (var project in baseline.Graph.Projects)
        {
            var errors = errorsByProject
                .Where(kv => kv.Key.StartsWith(project.Name, StringComparison.OrdinalIgnoreCase))
                .Select(kv => kv.Value)
                .DefaultIfEmpty(0)
                .First();
            var build = errors == 0 ? "✅ OK" : $"❌ {errors} error(s)";
            sb.AppendLine(
                $"| {project.Name} | `{project.TargetFramework}` | {project.ProjectReferences.Count} " +
                $"| {project.PackageReferences.Count} | {project.DocumentCount} | {build} |");
        }

        sb.AppendLine();
    }

    private static void AppendDependencyGraph(StringBuilder sb, BaselineResult baseline)
    {
        sb.AppendLine("## Project Dependency Graph");
        sb.AppendLine();

        if (baseline.Graph.Edges.Count == 0)
        {
            sb.AppendLine("_No project-to-project references detected._");
            sb.AppendLine();
        }
        else
        {
            sb.AppendLine("```mermaid");
            sb.AppendLine("graph LR");
            foreach (var (from, to) in baseline.Graph.Edges)
                sb.AppendLine($"    {MermaidId(from)}[\"{from}\"] --> {MermaidId(to)}[\"{to}\"]");
            sb.AppendLine("```");
            sb.AppendLine();
        }

        if (baseline.Graph.Cycles.Count > 0)
        {
            sb.AppendLine("### ⚠️ Circular Dependencies");
            sb.AppendLine();
            foreach (var cycle in baseline.Graph.Cycles)
                sb.AppendLine($"- {string.Join(" → ", cycle)}");
            sb.AppendLine();
        }
    }

    private static void AppendComplexityHotspots(StringBuilder sb, BaselineResult baseline, int top)
    {
        var hotspots = baseline.ProjectSymbols
            .SelectMany(p => p.Symbols)
            .Where(s => s.Kind == SymbolKind.Method && s.Complexity > 1)
            .OrderByDescending(s => s.Complexity)
            .Take(top)
            .ToList();

        sb.AppendLine($"## Complexity Hotspots (top {top} methods)");
        sb.AppendLine();
        if (hotspots.Count == 0)
        {
            sb.AppendLine("_No methods with cyclomatic complexity above 1._");
            sb.AppendLine();
            return;
        }

        sb.AppendLine("| Complexity | Method | Project |");
        sb.AppendLine("|---:|---|---|");
        foreach (var symbol in hotspots)
            sb.AppendLine($"| {symbol.Complexity} | `{symbol.FullyQualifiedName}` | {symbol.ProjectName} |");
        sb.AppendLine();
    }

    private static void AppendDeprecatedSymbols(StringBuilder sb, BaselineResult baseline)
    {
        var deprecated = baseline.ProjectSymbols
            .SelectMany(p => p.Symbols)
            .Where(s => s.IsDeprecated)
            .ToList();

        sb.AppendLine("## Deprecated Symbols ([Obsolete])");
        sb.AppendLine();
        if (deprecated.Count == 0)
        {
            sb.AppendLine("_No [Obsolete] symbols declared in source._");
            sb.AppendLine();
            return;
        }

        sb.AppendLine($"{deprecated.Count} symbol(s) marked [Obsolete]:");
        sb.AppendLine();
        foreach (var symbol in deprecated.Take(25))
            sb.AppendLine($"- `{symbol.FullyQualifiedName}` ({symbol.ProjectName})");
        if (deprecated.Count > 25)
            sb.AppendLine($"- _...and {deprecated.Count - 25} more (see `symbols` table in legacylens.db)_");
        sb.AppendLine();
    }

    private static void AppendAppCat(StringBuilder sb, BaselineResult baseline)
    {
        sb.AppendLine("## AppCAT Incidents");
        sb.AppendLine();
        if (baseline.AppCat is null)
        {
            sb.AppendLine("_No AppCAT report supplied. Run `dotnet appcat` and pass `--appcat <report.json>` to include incident mapping._");
            sb.AppendLine();
            return;
        }

        sb.AppendLine($"Source: `{baseline.AppCat.SourcePath}` — {baseline.AppCat.Incidents.Count} incident(s).");
        sb.AppendLine();
        sb.AppendLine("| Severity | Count |");
        sb.AppendLine("|---|---:|");
        foreach (var (severity, count) in baseline.AppCat.CountsBySeverity.OrderByDescending(kv => kv.Value))
            sb.AppendLine($"| {severity} | {count} |");
        sb.AppendLine();

        var topRules = baseline.AppCat.Incidents
            .GroupBy(i => i.RuleId, StringComparer.OrdinalIgnoreCase)
            .OrderByDescending(g => g.Count())
            .Take(10)
            .ToList();

        sb.AppendLine("### Top Rules");
        sb.AppendLine();
        sb.AppendLine("| Rule | Incidents | Example |");
        sb.AppendLine("|---|---:|---|");
        foreach (var group in topRules)
        {
            var example = group.First().Description ?? group.First().File ?? "—";
            sb.AppendLine($"| `{group.Key}` | {group.Count()} | {Truncate(example, 80)} |");
        }

        sb.AppendLine();
    }

    private static void AppendWorkspaceDiagnostics(StringBuilder sb, BaselineResult baseline)
    {
        if (baseline.WorkspaceDiagnostics.Count == 0)
            return;

        sb.AppendLine("## Workspace Load Diagnostics");
        sb.AppendLine();
        sb.AppendLine($"{baseline.WorkspaceDiagnostics.Count} non-fatal workspace diagnostic(s):");
        sb.AppendLine();
        foreach (var diagnostic in baseline.WorkspaceDiagnostics.Take(25))
            sb.AppendLine($"- {Truncate(diagnostic, 200)}");
        if (baseline.WorkspaceDiagnostics.Count > 25)
            sb.AppendLine($"- _...and {baseline.WorkspaceDiagnostics.Count - 25} more_");
        sb.AppendLine();
    }

    private static string MermaidId(string name) =>
        new([.. name.Select(c => char.IsLetterOrDigit(c) ? c : '_')]);

    private static string Truncate(string value, int max) =>
        value.Length <= max ? value : value[..max] + "…";
}
